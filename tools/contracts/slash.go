package main

import (
	"bytes"
	"encoding/json"

	"github.com/hailam/mig33/internal/slashcommands"
)

const slashCommandsPath = "apps/mobile/src/mig33/generated/slash-commands.ts"

// generateSlashCommands projects Go-owned suggestion metadata, independently of
// the recovered packet definitions and their original-JAR evidence hashes.
func generateSlashCommands() ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(`// Generated by sh scripts/generate-contracts.sh. DO NOT EDIT.
// Source: internal/slashcommands/catalog.go — local supported-command metadata.
// This is not an original wire registry or a client authorization policy.

export interface SlashCommandDefinition {
  readonly id: string;
  readonly command: string;
  readonly usage: string;
  readonly description: string;
  readonly insert: string;
  readonly arguments: 'none' | 'optional' | 'required';
  readonly scope: 'all' | 'room' | 'community';
  readonly requirement?: string;
  readonly allowMuted: boolean;
  readonly parent?: string;
  readonly aliases?: readonly string[];
}

export const slashCommands = `)
	var data bytes.Buffer
	encoder := json.NewEncoder(&data)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(slashcommands.Catalog()); err != nil {
		return nil, err
	}
	output.Write(bytes.TrimSuffix(data.Bytes(), []byte("\n")))
	output.WriteString(" as const satisfies readonly SlashCommandDefinition[];\n")
	return output.Bytes(), nil
}
