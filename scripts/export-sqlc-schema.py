#!/usr/bin/env python3
"""Build sqlc's schema snapshot without opening any application database.

Numbered SQL files in db/migrations are the shared migration source. Their DDL
is applied to an empty in-memory SQLite database, including table rebuilds and
column additions. V2's Go high-water-mark preservation is unnecessary for an
empty schema. TestSQLCSchemaMatchesMigrations verifies the resulting snapshot
against the real migration runner.
"""

import argparse
import pathlib
import re
import sqlite3


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing a stale snapshot")
    args = parser.parse_args()
    root = pathlib.Path(__file__).resolve().parent.parent
    migrations = {}
    for source in sorted((root / "db/migrations").glob("*.sql")):
        match = re.fullmatch(r"(\d{3})\.sql", source.name)
        if match is None:
            raise SystemExit(f"Invalid migration filename: {source.name}; use NNN.sql")
        version = int(match.group(1))
        if version in migrations:
            raise SystemExit(f"Duplicate migration schema V{version}")
        migrations[version] = source.read_text()
    if not migrations or set(migrations) != set(range(1, max(migrations) + 1)):
        raise SystemExit("Incomplete migration SQL catalog; versions must be contiguous from 001")
    with sqlite3.connect(":memory:") as database:
        database.execute("PRAGMA foreign_keys=ON")
        for _, ddl in sorted(migrations.items()):
            database.executescript(ddl)
        statements = database.execute(
            "SELECT sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END,name"
        ).fetchall()
    content = (
        "-- Generated by scripts/export-sqlc-schema.py; do not edit.\n"
        "-- Runtime upgrades use db/migrations via internal/adapters/sqlite/migrations.\n\n"
        + "\n\n".join(statement[0] + ";" for statement in statements)
        + "\n"
    )
    destination = root / "db/schema.sql"
    if args.check:
        if not destination.exists() or destination.read_text() != content:
            raise SystemExit("db/schema.sql is stale; run scripts/generate-sqlc.sh")
    else:
        destination.write_text(content)


if __name__ == "__main__":
    main()
